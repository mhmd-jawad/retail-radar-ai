async def create_roadmap(
    db_url: str,
    tenant_id: UUID,
    recommendation_id: str,
    sku_id: str,
    product_name: str,
    decision_type: str,
    confidence_pct: float,
    suggested_discount_pct: float | None,
    context: dict[str, str] | None = None,
) -> int:
    """
    Create a new roadmap for a recommendation.
    Idempotent — returns existing id if the recommendation_id already has a roadmap.
    Returns the roadmap id.
    """
    conf = round(confidence_pct * 100, 1) if confidence_pct and confidence_pct <= 1.0 else (confidence_pct or 0)
    ctx = context or {}

    conn = await psycopg.AsyncConnection.connect(db_url, row_factory=dict_row)
    try:
        async with conn.cursor() as cur:
            await cur.execute(
                """
                INSERT INTO whatsapp.recommendation_roadmaps
                    (tenant_id, recommendation_id, sku_id, product_name, decision_type,
                     confidence_pct, suggested_discount_pct,
                     context_summary, reasoning, expected_impact,
                     risks, alternatives, next_best_step)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                ON CONFLICT (recommendation_id) DO NOTHING
                RETURNING id
                """,
                (
                    str(tenant_id), recommendation_id, sku_id, product_name,
                    decision_type.upper(), conf, suggested_discount_pct,
                    ctx.get("context_summary"), ctx.get("reasoning"),
                    ctx.get("expected_impact"), ctx.get("risks"),
                    ctx.get("alternatives"), ctx.get("next_best_step"),
                ),
            )
            row = await cur.fetchone()
        await conn.commit()

        if row:
            roadmap_id = int(row["id"])
            await _append_audit(db_url, roadmap_id, "roadmap_created", "system",
                                to_stage="recommendation_ready")
            return roadmap_id

        # Already existed — fetch
        async with conn.cursor() as cur:
            await cur.execute(
                "SELECT id FROM whatsapp.recommendation_roadmaps WHERE recommendation_id = %s",
                (recommendation_id,),
            )
            existing = await cur.fetchone()
        return int(existing["id"]) if existing else -1
    finally:
        await conn.close()


async def advance_stage(
    db_url: str,
    roadmap_id: int,
    new_stage: str,
    actor: str = "system",
    notes: str | None = None,
    extra_updates: dict[str, Any] | None = None,
) -> None:
    """Advance a roadmap to a new stage and write an audit entry."""
    conn = await psycopg.AsyncConnection.connect(db_url, row_factory=dict_row)
    try:
        async with conn.cursor() as cur:
            await cur.execute(
                "SELECT current_stage FROM whatsapp.recommendation_roadmaps WHERE id = %s",
                (roadmap_id,),
            )
            row = await cur.fetchone()
        if not row:
            return
        old_stage = row["current_stage"]

        set_parts = ["current_stage = %s"]
        values: list[Any] = [new_stage]

        ts_map = {
            "approved": "approved_at",
            "executing": "executed_at",
            "completed": "completed_at",
        }
        if new_stage in ts_map:
            set_parts.append(f"{ts_map[new_stage]} = NOW()")

        if extra_updates:
            for k, v in extra_updates.items():
                set_parts.append(f"{k} = %s")
                values.append(v)

        values.append(roadmap_id)
        async with conn.cursor() as cur:
            await cur.execute(
                f"UPDATE whatsapp.recommendation_roadmaps SET {', '.join(set_parts)} WHERE id = %s",
                values,
            )
        await conn.commit()
    finally:
        await conn.close()

    await _append_audit(
        db_url, roadmap_id, f"stage → {new_stage}", actor,
        from_stage=old_stage, to_stage=new_stage,
        details={"notes": notes} if notes else None,
    )


