async def get_roadmap_summary(db_url: str, tenant_id: UUID) -> dict[str, Any]:
    """Management-level view of all roadmaps for this tenant (last 30 days)."""
    conn = await psycopg.AsyncConnection.connect(db_url, row_factory=dict_row)
    try:
        async with conn.cursor() as cur:
            await cur.execute(
                """
                SELECT
                    id, sku_id, product_name, decision_type, current_stage,
                    confidence_pct, suggested_discount_pct,
                    reasoning, expected_impact, next_best_step,
                    modification_count, last_modification,
                    approved_at, executed_at, completed_at,
                    outcome_velocity_lift_pct, outcome_revenue_delta_usd,
                    created_at, expires_at
                FROM whatsapp.recommendation_roadmaps
                WHERE tenant_id = %s
                  AND created_at > NOW() - INTERVAL '30 days'
                ORDER BY
                    CASE current_stage
                        WHEN 'awaiting_approval'    THEN 1
                        WHEN 'blocked'              THEN 2
                        WHEN 'modified'             THEN 3
                        WHEN 'recommendation_ready' THEN 4
                        WHEN 'approved'             THEN 5
                        WHEN 'executing'            THEN 6
                        WHEN 'monitoring'           THEN 7
                        WHEN 'reviewing'            THEN 8
                        WHEN 'completed'            THEN 9
                        ELSE 10
                    END,
                    created_at DESC
                """,
                (str(tenant_id),),
            )
            rows = await cur.fetchall()
    finally:
        await conn.close()

    now = datetime.now(tz=timezone.utc)

    def _age_hours(ts: Any) -> float:
        if ts is None:
            return 0.0
        if ts.tzinfo is None:
            ts = ts.replace(tzinfo=timezone.utc)
        return round((now - ts).total_seconds() / 3600, 1)

    items = []
    by_stage: dict[str, list] = {}
    for r in rows:
        stage = r["current_stage"]
        item = {
            "roadmap_id": r["id"],
            "sku_id": r["sku_id"],
            "product_name": r["product_name"],
            "decision_type": r["decision_type"],
            "stage": STAGE_LABELS.get(stage, stage),
            "stage_key": stage,
            "confidence_pct": float(r["confidence_pct"] or 0),
            "suggested_discount_pct": float(r["suggested_discount_pct"] or 0),
            "reasoning": r["reasoning"] or "",
            "expected_impact": r["expected_impact"] or "",
            "next_best_step": r["next_best_step"] or "",
            "modification_count": r["modification_count"],
            "last_modification": r["last_modification"],
            "approved_at": r["approved_at"].isoformat() if r["approved_at"] else None,
            "outcome_velocity_lift_pct": float(r["outcome_velocity_lift_pct"]) if r["outcome_velocity_lift_pct"] else None,
            "outcome_revenue_delta_usd": float(r["outcome_revenue_delta_usd"]) if r["outcome_revenue_delta_usd"] else None,
            "age_hours": _age_hours(r["created_at"]),
        }
        items.append(item)
        by_stage.setdefault(stage, []).append(item)

    needs_attention = [i for i in items if i["stage_key"] in ("awaiting_approval", "blocked", "modified")]

    return {
        "total": len(items),
        "stage_counts": {s: len(v) for s, v in by_stage.items()},
        "by_stage": by_stage,
        "needs_attention": needs_attention,
        "needs_attention_count": len(needs_attention),
    }


async def get_recommendation_detail(db_url: str, roadmap_id: int) -> dict[str, Any]:
    """Full detail for a single roadmap including audit trail."""
    conn = await psycopg.AsyncConnection.connect(db_url, row_factory=dict_row)
    try:
        async with conn.cursor() as cur:
            await cur.execute(
                "SELECT * FROM whatsapp.recommendation_roadmaps WHERE id = %s",
                (roadmap_id,),
            )
            roadmap = await cur.fetchone()
            if not roadmap:
                return {"error": f"Roadmap {roadmap_id} not found"}
            await cur.execute(
                """
                SELECT action, actor, from_stage, to_stage, details, created_at
                FROM whatsapp.roadmap_audit_log
                WHERE roadmap_id = %s
                ORDER BY created_at
                """,
                (roadmap_id,),
            )
            audit = await cur.fetchall()
    finally:
        await conn.close()

    return {
        "roadmap": {k: (v.isoformat() if isinstance(v, datetime) else v) for k, v in dict(roadmap).items()},
        "stage_label": STAGE_LABELS.get(roadmap["current_stage"], roadmap["current_stage"]),
        "audit_trail": [
            {**{k: (v.isoformat() if isinstance(v, datetime) else v) for k, v in dict(a).items()}}
            for a in audit
        ],
    }


async def get_next_actions(db_url: str, tenant_id: UUID) -> dict[str, Any]:
    """Prioritised action list for management: what needs attention right now."""
    conn = await psycopg.AsyncConnection.connect(db_url, row_factory=dict_row)
    try:
        async with conn.cursor() as cur:
            # Pending approvals
            await cur.execute(
                """
                SELECT sku_id, product_name, decision_type, confidence_pct,
                       suggested_discount_pct, reasoning, expected_impact,
                       ROUND(EXTRACT(EPOCH FROM (NOW() - created_at))/3600, 1) AS hours_waiting
                FROM whatsapp.recommendation_roadmaps
                WHERE tenant_id = %s AND current_stage = 'awaiting_approval'
                  AND (expires_at IS NULL OR expires_at > NOW())
                ORDER BY confidence_pct DESC NULLS LAST
                """,
                (str(tenant_id),),
            )
            pending = [dict(r) for r in await cur.fetchall()]

            # Modified — waiting for re-approval
            await cur.execute(
                """
                SELECT sku_id, product_name, decision_type,
                       modification_count, last_modification, confidence_pct
                FROM whatsapp.recommendation_roadmaps
                WHERE tenant_id = %s AND current_stage = 'modified'
                ORDER BY created_at DESC
                """,
                (str(tenant_id),),
            )
            modified = [dict(r) for r in await cur.fetchall()]

            # Blocked
            await cur.execute(
                """
                SELECT sku_id, product_name, decision_type, last_modification
                FROM whatsapp.recommendation_roadmaps
                WHERE tenant_id = %s AND current_stage = 'blocked'
                ORDER BY created_at DESC
                """,
                (str(tenant_id),),
            )
            blocked = [dict(r) for r in await cur.fetchall()]

            # Overdue: approved >7d but still in monitoring
            await cur.execute(
                """
                SELECT sku_id, product_name, decision_type,
                       ROUND(EXTRACT(EPOCH FROM (NOW() - approved_at))/86400, 1) AS days_since_approval
                FROM whatsapp.recommendation_roadmaps
                WHERE tenant_id = %s
                  AND current_stage IN ('approved','executing','monitoring')
                  AND approved_at < NOW() - INTERVAL '7 days'
                ORDER BY approved_at
                """,
                (str(tenant_id),),
            )
            overdue = [dict(r) for r in await cur.fetchall()]

            # Recently completed with results
            await cur.execute(
                """
                SELECT sku_id, product_name, decision_type,
                       outcome_velocity_lift_pct, outcome_revenue_delta_usd,
                       completed_at
                FROM whatsapp.recommendation_roadmaps
                WHERE tenant_id = %s AND current_stage = 'completed'
                  AND completed_at > NOW() - INTERVAL '14 days'
                ORDER BY completed_at DESC
                LIMIT 3
                """,
                (str(tenant_id),),
            )
            completed = [dict(r) for r in await cur.fetchall()]
    finally:
        await conn.close()

    if pending:
        priority = f"You have {len(pending)} recommendation(s) waiting for your approval."
    elif modified:
        priority = f"{len(modified)} modified recommendation(s) need re-approval."
    elif overdue:
        priority = f"{len(overdue)} approved action(s) are overdue for their performance review."
    elif blocked:
        priority = f"{len(blocked)} item(s) are blocked and need attention."
    else:
        priority = "No urgent actions pending — pipeline is clear."

    return {
        "priority_action": priority,
        "pending_approvals": pending,
        "modified_pending_reapproval": modified,
        "blocked_items": blocked,
        "overdue_review": overdue,
        "recently_completed": [
            {**r, "completed_at": r["completed_at"].isoformat() if r.get("completed_at") else None}
            for r in completed
        ],
    }


# ── Rich context generation ────────────────────────────────────────────────────

async def generate_rich_context(
    anthropic_api_key: str,
    product_name: str,
    decision_type: str,
    confidence_pct: float,
    suggested_discount_pct: float | None,
    explanation: str,
    retail_price: float,
    cost_price: float,
) -> dict[str, str]:
    """
    Use Claude Haiku to generate structured recommendation context:
    reasoning, expected impact, risks, alternatives, next best step.
    Falls back to template values if the API call fails.
    """
    import anthropic as _anthropic

    discount_line = f"{int(suggested_discount_pct)}% discount" if suggested_discount_pct else "pricing action"
    new_price = retail_price * (1 - (suggested_discount_pct or 0) / 100)
    margin_after = ((new_price - cost_price) / new_price * 100) if new_price > 0 else 0

    prompt = f"""You are a retail business analyst for StylePulse, a sportswear retailer in Lebanon.
Generate a structured recommendation context for the retailer to review via WhatsApp.

Product: {product_name}
Decision: {decision_type} — {discount_line}
AI confidence: {confidence_pct:.0f}%
Primary signal: {explanation}
Retail price: ${retail_price:.2f}  |  New price after discount: ${new_price:.2f}
Margin after action: {margin_after:.1f}%

Return ONLY a JSON object with these exact keys (no markdown, no explanation):
- context_summary: 1-2 sentences — which data signals triggered this recommendation
- reasoning: 2-3 sentences — WHY this action makes sense right now
- expected_impact: 1-2 sentences — expected outcome (units sold, revenue, margin)
- risks: 1 sentence — the main risk of taking this action
- alternatives: 1 sentence — what else could be done instead
- next_best_step: 1 short sentence — the single most important thing to do next"""

    try:
        client = _anthropic.AsyncAnthropic(api_key=anthropic_api_key)
        response = await client.messages.create(
            model="claude-haiku-4-5-20251001",
            max_tokens=600,
            messages=[{"role": "user", "content": prompt}],
        )
        text = (response.content[0].text if response.content else "").strip()
        if text.startswith("```"):
            text = text.split("```", 2)[1]
            if text.startswith("json"):
                text = text[4:]
            text = text.rsplit("```", 1)[0].strip()
        return json.loads(text)
    except Exception as exc:
        logger.warning("Rich context generation failed for %s: %s", product_name, exc)
        return {
            "context_summary": f"Inventory and pricing signals indicate action needed on {product_name}.",
            "reasoning": explanation or "AI confidence threshold met based on current stock and velocity data.",
            "expected_impact": f"Expected revenue improvement from applying {discount_line}.",
            "risks": "Margin compression if discount is deeper than needed — monitor closely.",
            "alternatives": "Hold price for one more week and monitor sales velocity.",
            "next_best_step": f"Review and approve the {decision_type.lower()} recommendation.",
        }


