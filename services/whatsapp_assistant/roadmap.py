# ── Schema migration ───────────────────────────────────────────────────────────

async def ensure_roadmap_tables(db_url: str) -> None:
    """Idempotent migration — creates all roadmap tracking tables."""
    conn = await psycopg.AsyncConnection.connect(db_url)
    try:
        async with conn.cursor() as cur:
            await cur.execute(
                """
                CREATE TABLE IF NOT EXISTS whatsapp.recommendation_roadmaps (
                    id                        BIGSERIAL    PRIMARY KEY,
                    tenant_id                 UUID         NOT NULL REFERENCES core.tenants(id) ON DELETE CASCADE,
                    recommendation_id         UUID         REFERENCES marketing.recommendations(id) ON DELETE SET NULL,
                    sku_id                    TEXT         NOT NULL,
                    product_name              TEXT         NOT NULL,
                    decision_type             TEXT         NOT NULL
                                              CHECK (decision_type IN ('PROMOTE','MARKDOWN','CLEAR','HOLD')),
                    current_stage             TEXT         NOT NULL DEFAULT 'recommendation_ready'
                                              CHECK (current_stage IN (
                                                  'discovery','recommendation_ready','awaiting_approval',
                                                  'approved','modified','executing','monitoring',
                                                  'reviewing','completed','blocked','expired'
                                              )),
                    -- Rich context generated by Claude Haiku
                    context_summary           TEXT,
                    reasoning                 TEXT,
                    expected_impact           TEXT,
                    risks                     TEXT,
                    alternatives              TEXT,
                    next_best_step            TEXT,
                    -- Metrics snapshot at recommendation time
                    confidence_pct            NUMERIC(5,2),
                    suggested_discount_pct    NUMERIC(5,2),
                    -- Lifecycle timestamps
                    created_at                TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
                    approved_at               TIMESTAMPTZ,
                    executed_at               TIMESTAMPTZ,
                    completed_at              TIMESTAMPTZ,
                    last_followup_at          TIMESTAMPTZ,
                    next_followup_at          TIMESTAMPTZ  DEFAULT NOW() + INTERVAL '4 hours',
                    expires_at                TIMESTAMPTZ  DEFAULT NOW() + INTERVAL '24 hours',
                    -- Outcome (populated after 7d/14d measurement)
                    outcome_snapshot_id       BIGINT       REFERENCES outcome_tracking.decision_snapshots(id) ON DELETE SET NULL,
                    outcome_velocity_lift_pct NUMERIC(8,2),
                    outcome_revenue_delta_usd NUMERIC(12,2),
                    -- Modification tracking
                    modification_count        INTEGER      NOT NULL DEFAULT 0,
                    last_modification         TEXT,
                    -- Dedup
                    UNIQUE (recommendation_id)
                )
                """
            )
            await cur.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_roadmaps_tenant_stage
                    ON whatsapp.recommendation_roadmaps (tenant_id, current_stage, created_at DESC)
                """
            )
            await cur.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_roadmaps_followup
                    ON whatsapp.recommendation_roadmaps (next_followup_at)
                    WHERE current_stage NOT IN ('completed','expired','blocked')
                """
            )
            await cur.execute(
                """
                CREATE TABLE IF NOT EXISTS whatsapp.roadmap_audit_log (
                    id          BIGSERIAL    PRIMARY KEY,
                    roadmap_id  BIGINT       NOT NULL REFERENCES whatsapp.recommendation_roadmaps(id) ON DELETE CASCADE,
                    action      TEXT         NOT NULL,
                    actor       TEXT         NOT NULL CHECK (actor IN ('retailer','system','ai')),
                    from_stage  TEXT,
                    to_stage    TEXT,
                    details     JSONB,
                    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
                )
                """
            )
            await cur.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_roadmap_audit_roadmap
                    ON whatsapp.roadmap_audit_log (roadmap_id, created_at)
                """
            )
        await conn.commit()
    finally:
        await conn.close()


