async def roadmap_followup_loop(
    db_url: str,
    retailer_phone: str,
    tenant_id: UUID,
    wa_client: Any,
    interval_seconds: int = 3600,
) -> None:
    """
    Background task: every hour, check for roadmaps that need a follow-up nudge.
    Sends a WhatsApp reminder if a recommendation has been waiting for approval
    for more than 4 hours without a response.
    """
    import asyncio
    while True:
        await asyncio.sleep(interval_seconds)
        try:
            conn = await psycopg.AsyncConnection.connect(db_url, row_factory=dict_row)
            try:
                async with conn.cursor() as cur:
                    await cur.execute(
                        """
                        SELECT id, product_name, decision_type, confidence_pct,
                               suggested_discount_pct, reasoning,
                               ROUND(EXTRACT(EPOCH FROM (NOW() - created_at))/3600, 0) AS hours_waiting
                        FROM whatsapp.recommendation_roadmaps
                        WHERE tenant_id = %s
                          AND current_stage IN ('awaiting_approval', 'modified')
                          AND (next_followup_at IS NULL OR next_followup_at <= NOW())
                          AND (expires_at IS NULL OR expires_at > NOW())
                        ORDER BY created_at
                        LIMIT 3
                        """,
                        (str(tenant_id),),
                    )
                    due = await cur.fetchall()
            finally:
                await conn.close()

            for row in due:
                hours = int(row["hours_waiting"] or 0)
                discount = int(row["suggested_discount_pct"] or 0)
                action = "modified and awaiting re-approval" if "modified" in str(row) else "waiting for your approval"
                msg = (
                    f"⏰ *Reminder — Action Needed*\n\n"
                    f"*{row['decision_type']}: {row['product_name']}*\n"
                    f"Discount: *{discount}%* off · Confidence: *{int(row['confidence_pct'] or 0)}%*\n"
                    f"Reason: {row['reasoning'] or 'AI confidence threshold met'}\n\n"
                    f"This recommendation has been {action} for *{hours}h*.\n\n"
                    f"Reply *APPROVE*, *MODIFY [instruction]*, or *REJECT*.\n"
                    f"_(Or ask me: 'What should we do about {row['product_name']}?')_"
                )
                try:
                    await wa_client.send_text_message(retailer_phone, msg)
                    # Push next follow-up 4 hours out
                    conn2 = await psycopg.AsyncConnection.connect(db_url)
                    try:
                        async with conn2.cursor() as cur:
                            await cur.execute(
                                """
                                UPDATE whatsapp.recommendation_roadmaps
                                SET last_followup_at = NOW(),
                                    next_followup_at = NOW() + INTERVAL '4 hours'
                                WHERE id = %s
                                """,
                                (row["id"],),
                            )
                        await conn2.commit()
                    finally:
                        await conn2.close()
                    await _append_audit(db_url, int(row["id"]), "followup_sent", "system")
                    logger.info("Follow-up reminder sent for roadmap %s (%s)", row["id"], row["product_name"])
                except Exception as exc:
                    logger.warning("Follow-up send failed for roadmap %s: %s", row["id"], exc)

        except Exception as exc:
            logger.error("Roadmap follow-up loop error: %s", exc, exc_info=True)


# ── Audit helper ───────────────────────────────────────────────────────────────

async def _append_audit(
    db_url: str,
    roadmap_id: int,
    action: str,
    actor: str,
    from_stage: str | None = None,
    to_stage: str | None = None,
    details: dict | None = None,
) -> None:
    conn = await psycopg.AsyncConnection.connect(db_url)
    try:
        async with conn.cursor() as cur:
            await cur.execute(
                """
                INSERT INTO whatsapp.roadmap_audit_log
                    (roadmap_id, action, actor, from_stage, to_stage, details)
                VALUES (%s, %s, %s, %s, %s, %s)
                """,
                (
                    roadmap_id, action, actor, from_stage, to_stage,
                    json.dumps(details) if details else None,
                ),
            )
        await conn.commit()
    except Exception as exc:
        logger.debug("Audit log write failed: %s", exc)
    finally:
        await conn.close()
